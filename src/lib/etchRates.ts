export function getEtchRecipes(flowRecipes?: EtchRecipe[]): EtchRecipe[] {
  if (!flowRecipes || flowRecipes.length === 0) {
    return DEFAULT_ETCH_RECIPES;
  }
  const byId = new Map<string, EtchRecipe>();
  for (const r of DEFAULT_ETCH_RECIPES) {
    byId.set(r.id, r);
  }
  for (const r of flowRecipes) {
    byId.set(r.id, r);
  }
  return Array.from(byId.values());
}

export function getEtchRecipeById(
  flowRecipes: EtchRecipe[] | undefined,
  recipeId?: string
): EtchRecipe | undefined {
  if (!recipeId) return undefined;
  return getEtchRecipes(flowRecipes).find((r) => r.id === recipeId);
}

export function getEtchRateNmMin(recipe: EtchRecipe, materialId: string): number {
  if (Object.prototype.hasOwnProperty.call(recipe.rates, materialId)) {
    const val = recipe.rates[materialId];
    return typeof val === 'number' && Number.isFinite(val) ? Math.max(0, val) : 0;
  }
  return Math.max(0, recipe.defaultRateNmMin ?? 0);
}

export function computeSelectivityRatio(
  targetRate: number,
  maskOrStopRate: number
): string {
  if (targetRate <= 0) return '0:1';
  if (maskOrStopRate <= 0) return '∞ : 1';
  const ratio = targetRate / maskOrStopRate;
  if (ratio >= 100) return `${Math.round(ratio)}:1`;
  if (ratio >= 10) return `${ratio.toFixed(1)}:1`;
  return `${ratio.toFixed(2)}:1`;
}

export function formatEtchRate(rateNmMin: number, unit: ThicknessUnit = 'nm'): string {
  if (rateNmMin <= 0) return unit === 'um' ? '0 µm/min' : '0 nm/min';
  if (unit === 'um') {
    const um = rateNmMin / 1000;
    const rounded =
      um >= 10 ? um.toFixed(2) : um >= 1 ? um.toFixed(3) : um.toFixed(4);
    return `${parseFloat(rounded)} µm/min`;
  }
  const formatted =
    rateNmMin >= 10 ? Math.round(rateNmMin).toLocaleString() : Number(rateNmMin.toFixed(2)).toString();
  return `${formatted} nm/min`;
}

export function formatDurationCompact(seconds: number): string {
  if (!Number.isFinite(seconds) || seconds <= 0) return '0 s';
  if (seconds < 60) {
    return `${seconds >= 10 ? Math.round(seconds) : Number(seconds.toFixed(1))} s`;
  }
  const mins = seconds / 60;
  if (mins < 60) {
    return `${Number(mins.toFixed(2))} min`;
  }
  return `${Number((mins / 60).toFixed(2))} hr`;
}
